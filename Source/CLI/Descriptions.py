from dublib.CLI.Terminalyzer import Command, ValidableTypes
from dublib.CLI.TextStyler import GetStyledTextFromHTML

COMMANDS: list[Command] = list()

Com = Command("build-manga", "Build manga read-ready manga content.")
ComPos = Com.create_position("FILE", "Filename of local JSON.", important = True)
ComPos.set_argument()
ComPos = Com.create_position("PARSER", "Name of parser.", important = True)
ComPos.add_key("--use")
ComPos = Com.create_position("TARGET", "Target for building. By default longest branch.")
ComPos.add_key("--branch", type = ValidableTypes.UnsignedInteger, description = "Branch ID.")
ComPos.add_key("--chapter", type = ValidableTypes.UnsignedInteger, description = "Chapter ID.")
ComPos = Com.create_position("FORMAT", "Format of output content. By default downloads images in folder.")
ComPos.add_flag("-zip", description = "Make *.ZIP archives.")
ComPos.add_flag("-cbz", description = "Make *.CBZ files.")
ComPos.add_flag("-pdf", description = "Make *.CBZ files.")
Com.base.add_key("--cnt", description = "Template for chapters naming.")
Com.base.add_key("--vnt", description = "Template for volumes naming.")
Com.base.add_flag("-s", description = "Enable chapters sorting by volumes directories.")
COMMANDS.append(Com)

Com = Command("cacher", "Run ID-slug caching.")
ComPos = Com.create_position("PARSERS", "One or more parsers names separated by comma. By default all.")
ComPos.add_key("--use")
COMMANDS.append(Com)

Com = Command("classify", "Process titles classificators.")
ComPos = Com.create_position("VALUE", "Input value to classification.", important = True)
ComPos.set_argument()
ComPos = Com.create_position("MODE", "Output mode. By default styled print to terminal.")
ComPos.add_flag("-j", aliases = ("--json",), description = "Prints JSON-string in terminal.")
ComPos.add_key("--file", type = ValidableTypes.Path, description = "Path to dump JSON file.")
Com.base.add_flag("-i", aliases = ("--ignorecase",), description = "Ignore characters case in procedures searching.")
COMMANDS.append(Com)

Com = Command("collect", GetStyledTextFromHTML("Collect titles slugs into <i>Collection.txt</i> file in parser's temporary directory."))
ComPos = Com.create_position("PARSER", "Name of parser.", important = True)
ComPos.add_key("--use")
Com.base.add_flag("-f", description = "Enable force mode.")
Com.base.add_flag("-local", description = "Scan local titles and put into collection.")
Com.base.add_flag("-no-sort", description = "Disable slugs sorting.")
Com.base.add_key("--filters", description = "Query string for filtering titles.")
Com.base.add_key("--pages", type = ValidableTypes.UnsignedInteger, description = "Count of pages to collecting.")
Com.base.add_key("--period", type = ValidableTypes.UnsignedInteger, description = "Period in hours for parsing updates.")
COMMANDS.append(Com)

Com = Command("fid", "Find title ID by slug in cache.")
ComPos = Com.create_position("SLUG", "Title slug.")
ComPos.set_argument()
ComPos = Com.create_position("PARSERS", "One or more parsers names separated by comma. By default all.")
ComPos.add_key("--use")
Com.base.add_flag("-all", description = "Print all search results instead only first.")
COMMANDS.append(Com)

Com = Command("get", "Download image in temporary parser directory by default.")
ComPos = Com.create_position("URL", "Link to image.", important = True)
ComPos.set_argument(ValidableTypes.URL)
ComPos = Com.create_position("PARSER", "Name of parser from which downloader will be used.", important = True)
ComPos.add_key("--use")
ComPos = Com.create_position("NAME", "Naming operation. By default save original.")
ComPos.add_key("--fullname", description = "Set full name with filename extension.")
ComPos.add_key("--name", description = "Rename, but save original filename extension.")
Com.base.add_flag("-f", description = "Enable force mode.")
Com.base.add_key("--dir", type = ValidableTypes.ValidPath, description = "Output directory.")
COMMANDS.append(Com)

Com = Command("list", "List installed parsers.")
COMMANDS.append(Com)

Com = Command("parse", "Parsing titles.")
ComPos = Com.create_position("TARGET", "Target for parsing.", important = True)
ComPos.set_argument(description = "Title slug.")
ComPos.add_key("--id", type = ValidableTypes.UnsignedInteger, description = "Title ID.")
ComPos.add_key("-collection", description = GetStyledTextFromHTML("Parse slugs from <i>Collection.txt</i> file."))
ComPos.add_flag("-local", description = "Parse all locally saved titles.")
ComPos.add_flag("-updates", description = "Parse titles updated for last 24 hours. Use key \"--period\" to change it.")
ComPos.add_flag("-last", description = "Parse last parsed title.")
ComPos = Com.create_position("PARSER", "Name of parser.", important = True)
ComPos.add_key("--use")
Com.base.add_flag("-f", description = "Enable force mode.")
Com.base.add_flag("-no-amend", description = "Disable chapters content amending.")
Com.base.add_flag("-no-images", description = "Disable covers and persons portraits downloading.")
Com.base.add_flag("-sort", description = "Enable chapters sorting after parsing.")
Com.base.add_key("--period", type = ValidableTypes.UnsignedInteger, description = "Period in hours for parsing. Use with \"-updates\" flag.")
Com.base.add_key("--from", description = "Skip titles before this slug.")
COMMANDS.append(Com)

Com = Command("repair", "Repair chapter chapter in local title.")
ComPos = Com.create_position("FILE", "Title filename with or without type.", important = True)
ComPos.set_argument()
ComPos = Com.create_position("TARGET", "Target to repairing.", important = True)
ComPos.add_key("--branch", type = ValidableTypes.UnsignedInteger, description = "Branch ID.")
ComPos.add_key("--chapter", type = ValidableTypes.UnsignedInteger, description = "Chapter ID.")
ComPos = Com.create_position("PARSER", "Name of parser.", important = True)
ComPos.add_key("--use")
COMMANDS.append(Com)